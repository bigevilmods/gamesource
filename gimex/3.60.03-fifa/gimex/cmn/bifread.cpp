#define BIFMAXLINE 512

int BIFisdigit(int c)
{
    int ok=0;

    if (c>='0' && c<='9')
        ok = 1;
    return(ok);
}

/****************************************************************/
/*  Get a String                                                */
/*  - used by BIFatoi                                           */
/****************************************************************/

static char    *BIFgetstring(char *buf, char *s)
{
    char c;
    char n;
    char *d;
    char firstc;
    char *olds;
    int numerr=0;

    d = buf;
    firstc = *s;
    olds = s;
    if (firstc==(char)'"')
    {
        do
        {
            ++s;
            do
            {
                c = *s++;
                if (c==(char)'\\')
                {
                    c = *s++;
                    switch(c)
                    {
                        case 'n':   *d++ = (char)10;    break;
                        case 't':   *d++ = (char)'\t';  break;
                        case 'b':   *d++ = (char)'\b';  break;
                        case 'r':   *d++ = (char)13;    break;
                        case 'f':   *d++ = (char)'\f';  break;
                        case '\\':  *d++ = (char)'\\';  break;
                        case '<':   *d++ = (char)'<';   break;
                        case '\'':	*d++ = (char)'\'';   break;
                        case '"':	*d++ = (char)'"'; break;
                        default:
                            c -= '0';
                            if ((unsigned char) c < (unsigned char) 8)
                            {
                                n = c;
                                c = (char)(*s++-'0');
                                if ((unsigned char) c < (unsigned char) 8)
                                {
                                    n = (char)(n*8+c);
                                    c = (char)(*s++-'0');
                                    if ((unsigned char) c < (unsigned char) 8)
                                    {
                                        if ((unsigned char) n >= (unsigned char) 32)
                                        {
                                            numerr = 1;
                                            n = 0;
                                            c = 0;
                                        }
                                        n = (char)(n*8+c);
                                        ++s;
                                    }
                                }
                                *d++ = n;
                            }
                            if (c==(char)8 || c==(char)9)
                            {
                                numerr = 2; /*Error(loc+(int)(s-olds), BadDigit); */
                                n = 0;
                                c = 0;
                            }
                            --s;
                            c = '0';
                            break;
                    }
                }
                else
                {
                    *d++ = c;
                }
            } while (c!=(char)'\0' && c!=(char)'"');
        } while (*s==(char)'"');

        if (c==(char)'"')
            *--d = '\0';                        /* remove close quote or slash */
        else
            --s;
    }
    else
    {
        if (firstc==(char)'\'')
        {
            do
            {
                ++s;
                do
                {
                    c = *s++;
                    *d++ = c;
                } while (c!=(char)'\0' && c!=(char)'\'');
            } while (*s==(char)'\'');

            if (c==(char)'\'')
                *--d = '\0';                    /* remove close quote or slash */
            else
                --s;
        }
        else
        {
            if (firstc==(char)'\\')
            {
                ++s;
            }

            do
            {
                c = *s++;
                *d++ = c;
            } while (c>' ' && c!=(char)';' && c!=(char)',');

            if (c)
            {
                *--d = '\0';                    /* remove ; or , or white space */
                if (*(d-1)==(char)'\\')
                    *--d = '\0';                /* remove slash */
            }
            else
                --s;

            if (firstc==(char)'\\')
            {
                numerr = 3; /*Error(loc+(int)(s-olds), Undef); */
            }
        }
    }
    if (numerr)
        s = "";

    return(s);
}


/****************************************************************/
/*  Get a Single Number                                         */
/****************************************************************/

int BIFatoiradix(char *s,int Radix)
{
    char                c;
    char                *opstart;
    char                *numstart;
    int                 base;
    int                nextval;
    int                 stringlen;
    char                buf[BIFMAXLINE];
    int numerr=0;


    if (*s<='@' || Radix>10)
    {
        c = *s++;
        if (*s)                                 /* more than 1 char? */
        {
            opstart = s;
            if (c<'0')
            {
                base = 16;
                if (c!=(char)'$')                       /* hex  */
                {
                    switch (c)
                    {
                        case '"':				/* start a string */
                        case '\'':
                            nextval = 0L;
                            s = BIFgetstring(buf, s-1);
                            if (*(s-1)!=(char)'"' && *(s-1)!=(char)'\'')    /* No closing delimiter */
                            {
                                numerr = 4; /*Error(loc, NoStrEnd); */
                            }
                            else
                            {
                                stringlen = strlen(buf);
                                if (stringlen>4)
                                {
                                    numerr = 5; /*Error(loc, SizeErr); */
                                }
                                else
                                {
                                    s = buf;
                                    while (stringlen--)
                                    {
                                        nextval = (nextval<<8) | (unsigned char) *s++;
                                    }
                                }
                            }
                            return(nextval);

                        case '%':               /* binary */
                            base = 2;
                            break;

                        case '&':               /* hex (arm style) */
                            base = 16;
                            break;

                        case 0:                 /* end of term */
                            numerr = 6; /*Error(loc, OperErr); */
                            return(0L);
                            break;

                        default:
                            base = 0;
                            break;
                    }
                }
            }
            else
            {
                base = Radix;
                --s;

                if (c==(char)'0')                       /* hex 0x */
                {
                    if (*(s+1)==(char)'x')
                    {
                        if (Radix<34)
                        {
                            base = 16;
                            s += 2;
                        }
                    }
                }
                else
                {
                    if (c==(char)'@')                   /* octal */
                    {
                        base = 8;
                        ++s;
                    }
                }
            }

            /* base 10 is optimized the most */

            nextval = 0L;
            if (base==10)
            {
                c = (char)(*s++-'0');
                if ((unsigned char) c < (unsigned char) 10)
                {
                    numstart = s;
                    nextval = (int) ((unsigned char) c);

                    c = (char)(*s++-'0');
                    if ((unsigned char) c < (unsigned char) 10)
                    {
                        nextval = (int) ((int) nextval * 10 + (unsigned char) c);

                        c = (char)(*s++-'0');
                        if ((unsigned char) c < (unsigned char) 10)
                        {
                            nextval = (int) ((int) nextval * 10 + (unsigned char) c);

                            c = (char)(*s++-'0');
                            if ((unsigned char) c < (unsigned char) 10)
                            {
                                do
                                {
                                    nextval = nextval * 10 + (unsigned char) c;

                                    c = (char)(*s++-'0');
                                } while ((unsigned char) c < (unsigned char) 10);
                            }
                        }
                    }
                    if (!*(s-1))    /* did we finish the number? */
                    {
                        /* more than 10 digits? */

                        if ((int)(s-numstart) > 10)
                          numerr = 7; /*Error(loc, SizeErr); */

                        return(nextval);
                    }
                }
            }
            else if (base==16)
            {
                c = (char)(*s++-'0');
                if ((unsigned char) c >= (unsigned char) 10)
                    c = (char)(((c+'0')|' ')-'a'+10);

                if ((unsigned char) c < (unsigned char) 16)
                {
                    numstart = s;
                    do
                    {
                        do
                        {
                            do
                            {
                                nextval = (nextval<<4) + (unsigned char) c;

                                c = (char)(*s++-'0');
                            } while ((unsigned char) c < (unsigned char) 10);

                            c = (char)(((c+'0')|' ')-'a'+10);

                        } while ((unsigned char) c < (unsigned char) 16);

                        if (*(s-1)==(char)'_')
                        {
                            ++numstart;             /* adjust start for len calc */
                            c = (char)(*s++-'0');
                            if ((unsigned char) c >= (unsigned char) 10)
                                c = (char)(((c+'0')|' ')-'a'+10);
                        }
                    } while ((unsigned char) c < (unsigned char) 16);

                    if (!*(s-1))                    /* did we finish the number? */
                    {
                        /* more than 8 digits? */

                        if ((int)(s-numstart) > 8)
                            numerr = 8; /*Error(loc, SizeErr); */

                        return(nextval);
                    }
                }
            }
            else
            {
                numstart = s;
                c = *s++;
                while (c)
                {
                    c -= '0';
                    if ((unsigned char) c >= (unsigned char) 10)
                        c = (char)(((c+'0')|' ')-'a'+10);

                    if ((unsigned char) c >= (unsigned char) base)
                    {
                        if (*(s-1)==(char)'_')
                        {
                            ++numstart;             /* adjust start for len calc */
                            continue;
                        }
                        break;
                    }

                    if ((unsigned int) nextval<3200L)
                    {
                        nextval = (int) nextval * base + (unsigned char) c;
                    }
                    else
                    {
                        nextval = (nextval*base) + (unsigned char) c;
                    }
                    c = *s++;
                }

                if (!*(s-1))                    /* did we finish the number? */
                {
                    /* more than 32 digits? */

                    if ((int)(s-numstart-1) > 32)
                        numerr = 9; /*Error(loc, SizeErr); */

                    return(nextval);
                }
            }

            if (*(s-1)==(char)'$')                          /* set base */
            {
                if (nextval>=2 && nextval<=34)
                {
                    base = Radix;
                    Radix = nextval;
                    nextval = BIFatoiradix(s,Radix);
                    Radix = base;
                    return(nextval);
                }
            }

            s = opstart-1;
            if (BIFisdigit(*s))                 /* was first char a digit */
            {
                while (*s)                      /* skip to the end */
                {
                    ++s;
                }

                c = *(s-1);
                *(s-1) = '\0';
                switch (c|' ')
                {
                    case 'b':
                        base = Radix;
                        Radix = 2;
                        nextval = BIFatoiradix(opstart-1,Radix);
                        Radix = base;
                        *(s-1) = c;
                        return(nextval);

                    case 'd':
                        base = Radix;
                        Radix = 10;
                        nextval = BIFatoiradix(opstart-1,Radix);
                        Radix = base;
                        *(s-1) = c;
                        return(nextval);

                    case 'h':
                        base = Radix;
                        Radix = 16;
                        nextval = BIFatoiradix(opstart-1,Radix);
                        Radix = base;
                        *(s-1) = c;
                        return(nextval);

                    case 'o':
                    case 'q':
                        base = Radix;
                        Radix = 8;
                        nextval = BIFatoiradix(opstart-1,Radix);
                        Radix = base;
                        *(s-1) = c;
                        return(nextval);
                    default:;
                }
                *(s-1) = c;
                s = opstart-1;
            }
        }
        else
        {
            c -= '0';
            if ((unsigned char) c >= (unsigned char) 10)
                c = (char)(((c+'0')|' ')-'a'+10);

            if ((unsigned char) c < (unsigned char) Radix)
            {
                return((int) c );
            }
            c = *--s;
        }
    }

    if (*s)
    {
        if (*s==(char)'^')                          /* control character */
        {
            if (!*(s+2))
            {
                c = (char)((*(s+1)|' ')-'a'+1);
                if ((unsigned char) c < (unsigned char) 27)
                {
                    return((int) c );
                }
            }
        }
    }
    numerr = 10; /* Error(loc, Undef); */
    return(0L);
}

int BIFatoi(char *s)
{
    return(BIFatoiradix(s,10));
}


static char *BIFgetcharfield(char *parsebuf, char *biffile, char *field)
{
    unsigned char *s= (unsigned char *)biffile;
    int fieldlen;
    char *d=0;

    fieldlen = strlen(field);

    while (*s)
    {
        while (*s && *s<=' ')       /* white space */
            ++s;
        if (!strncmp((char *)s,field,fieldlen))
        {
            while (*s && *s>' ')    /* not white space (skip field name) */
                ++s;
            while (*s && *s<=' ')   /* white space (skip spaces after field name) */
                ++s;
            d = parsebuf;
            while (*s && *s>' ')    /* not white space (fetch argument) */
                *d++ = *s++;
            *d++ = 0;
            d = parsebuf;
            break;
        }
        while (*s && *s>' ')
            ++s;
    }
    return(d);
}

static int BIFgetintfield(char *biffile, char *field)
{
    char *s;
    int val=-1;
    char parsebuf[80];

    s = BIFgetcharfield(parsebuf,biffile,field);
    if (s)
    {
        if (*s)
            val = BIFatoi(s);
        else
            val = 0;
    }
    return(val);
}

