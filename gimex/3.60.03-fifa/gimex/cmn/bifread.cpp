/* BIF stands for Binary Information File, and is a text file       */
/* script that describes a raw image file.                          */
/*                                                                  */
/* supported commands                                               */
/* BIF          required  identifies file as bif                    */
/* filename     optional  name of binary image file (assumes *.raw) */
/* width        required  width of image in pixels                  */
/* height       optional  height of image in pixels                 */
/* channels     optional  number of channels (1,3,or 4) 3 default   */
/* planes       optional  same as channels                          */
/* header       optional  size of header to skip in bytes           */
/* leftpadding  optional  number of left edge bytes to skip         */
/* rightpadding optional  number of right edge bytes to skip        */
/* order        optional  channel order g, rgb, bgr, argb, or bgra  */
/* upsidedown   optional  image is upside down                      */
/*                                                                  */
/* gimex extensions                                                 */
/* intel        extension image is intel byte ordering (for 16 bit) */
/* imageplanes  extension number of full image planes (psd style)   */
/* frames       extension number of frames                          */
/* framepadding extension number of bytes between frames            */
/*                                                                  */
/* unsupported commands                                             */
/* interleave             channel interleave 0=byte,1=line,2=plane  */
/* format                 ascii, group3, group4 (fax)               */
/* faxoptions             bitreversal                               */
/* bitspersample          may be 1, 8 or 16 (big endian by default) */
/* bitorder               msblsb or lsbmsb                          */
/* byteorder              motorola or intel                         */
/* signed                 by default 16 bit is unsigned             */
/*                                                                  */
/* Lines that begin with # are comments                             */
/* Numbers may be in hex, prefixed by 0x                            */
/* Filename may be specified more than once for planar files        */
/*   This feature is not supported by gimex                         */
/*                                                                  */
/* Example:                                                         */
/*                                                                  */
/* BIF                                                              */
/* filename astrnaut.tga                                            */
/* width      523                                                   */
/* height     478                                                   */
/* header      18                                                   */
/* channels     4                                                   */
/* order      bgra                                                  */
/* leftpadding  0                                                   */
/* rightpadding 0                                                   */
/* upsidedown                                                       */
/*                                                                  */
/* Extension: 2 channels changed meaning to 3 channels of 2 bytes,  */
/* for 16 bit formats. order still applies.  intel flag fetches     */
/* 2 bytes Intel style.  default is Motorola style.                 */
/*                                                                  */
/*------------------------------------------------------------------*/
