def GenerateShiftLeftConstant( shiftAmount ):
    return (
        0x00010203 + 0x01010101 * ( 0 + (shiftAmount)),
        0x00010203 + 0x01010101 * ( 4 + (shiftAmount)),
        0x00010203 + 0x01010101 * ( 8 + (shiftAmount)),
        0x00010203 + 0x01010101 * (12 + (shiftAmount))
        )

def ElementSelectWordConstant( index ):
    return 0x00010203 + 0x01010101 * (index * 4)

def ElementSelectHalfConstant( index ):
    return 0x0001 + 0x0101 * (index * 2)

# This function excepts either 4, 8 or 16 arguments
# Arguments are indices used to form permution constants.  If 4 indices are
# specified, a vector that selects word elements will be generated. If 8
# indices are specified, a vector that selects half word elements will be
# generated.  If 8 indices are specified, a vector that selects byte elements
# will be generated.
def VectorPermuteConstant( *indices ):
    if len(indices) == 4:
        return tuple( map(ElementSelectWordConstant,indices) )
    if len(indices) == 8:
        # Generate half words
        vectorWords = map(ElementSelectHalfConstant, indices )
        resultList = []
        for i in range(4):
            resultList.append( (vectorWords[2*i] << 16) | vectorWords[2*i+1] )
        return tuple(resultList)
    if len(indices) == 16:
        # Generate bytes
        resultList = []
        for i in range(4):
            resultList.append( (indices[4*i] << 24) | indices[4*i+1] << 16 | indices[4*i+2] << 8 | indices[4*i+3] )
        return tuple(resultList)

def GetByteInVector( vec, index ):
    def GetByteInInt32( int32, index ):
        # return the index'th byte (0 being the index of the MSB)
        return 0xff & (int32 >> (8*(3-index)))
    elementIndex = index / 4
    indexInElement = index % 4
    return GetByteInInt32( vec[elementIndex], indexInElement )

def GetByteInVectors( vectors, index ):
    vectorIndex = index / 16
    byteIndexInVector = index % 16
    return GetByteInVector( vectors[vectorIndex], byteIndexInVector )

def SetByteInVector( vec, index, byte ):
    def SetByteInInt32( int32, index, byte ):
        clearMask = 0xffffffff ^ (0xff << (8*(3-index)))
        return (int32 & clearMask) | (byte << (8*(3-index)))
    elements = list(vec)
    elementIndex = index / 4
    indexInElement = index % 4
    elements[elementIndex] = SetByteInInt32( elements[elementIndex], indexInElement, byte)
    return tuple(elements)

def VectorPermute( vecA, vecB, permuteVec ):
    result = (0, 0, 0, 0)
    for i in range(16):
        readIndex = GetByteInVector( permuteVec, i )
        byteValue = GetByteInVectors( (vecA, vecB), readIndex )
        result = SetByteInVector( result, i, byteValue )
    return result

