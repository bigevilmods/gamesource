    OutputVector( 'rw::math::vpu::detail::gCrossProductPermuteConstant',    VectorPermuteConstant(Y0, Z0, X0, W0) )

    OutputVectorArray( 'rw::math::vpu::detail::gSwizzleStoreConstants', swizzleConstants )

