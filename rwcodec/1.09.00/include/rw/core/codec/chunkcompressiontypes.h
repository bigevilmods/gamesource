#ifndef RW_CORE_CODEC_CHUNKCOMPRESSIONTYPES_H
#define RW_CORE_CODEC_CHUNKCOMPRESSIONTYPES_H

namespace rw {
namespace core {
namespace codec {

enum CHUNK_COMPRESSION_TYPE
{
    CHUNK_COMPRESSION_TYPE_FIRST = 1,
    CHUNK_COMPRESSION_TYPE_ZLIB = CHUNK_COMPRESSION_TYPE_FIRST,
    CHUNK_COMPRESSION_TYPE_REFPACK,
    // LZX decompression only works on XENON
    CHUNK_COMPRESSION_TYPE_LZX,                
    CHUNK_COMPRESSION_TYPE_UNCOMPRESSED,
    CHUNK_COMPRESSION_TYPE_LZMA,
    CHUNK_COMPRESSION_TYPE_LZ4,

    CHUNK_COMPRESSION_TYPE_UNKNOWN,
    CHUNK_COMPRESSION_TYPE_NUM,

    CHUNK_COMPRESSION_TYPE_FORCE_32_BIT = 0xFFFFFFFFUL
};

}}}

#endif //RW_CORE_CODEC_CHUNKCOMPRESSIONTYPES_H
